"""Builds engine/people_first.title: the main-menu art of the People First build.

Light blue and teal: a ring of people holding hands around a campfire under the stars (a back row and a front row),
the game's name above and the fork's line below.  engine/install_data.py copies it to data/title/people_first.title,
which only the patched exe reads (engine patch 11: it also prints "People First" under the version line).  The official
exe keeps the vanilla art.

The .title format: '#' lines are comments, color tags inline.  Vanilla art is at most 80 columns and 18 lines; this one is
108 x 24, which engine patch 25 centers and clips to the window.

Usage:  python engine/make_title.py          (writes the file and prints a plain preview)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
# 2026-10-16 (the user): 35% larger than the first version (80 x 18).  Engine patch 25 centers the art on its widest line.
W, H = 108, 24
C = 53                                 # the fire's column: the art is centered on it
grid = [[" "] * W for _ in range(H)]
color = [["light_cyan"] * W for _ in range(H)]


def put(row, col, text, col_name):
    for i, ch in enumerate(text):
        assert 0 <= col + i < W, (row, col, text)
        if ch != " ":
            grid[row][col + i] = ch
            color[row][col + i] = col_name


def centered(row, text, col_name):
    put(row, (W - len(text)) // 2, text, col_name)


def spaced(words):
    """'DARK DAYS' -> 'D  A  R  K     D  A  Y  S'"""
    return "     ".join("  ".join(w) for w in words.split())


# the name
centered(0, spaced("CATACLYSM : DARK DAYS AHEAD"), "light_blue")
# the sky
for col, ch in ((8, "."), (30, "*"), (77, "*"), (99, ".")):
    put(2, col, ch, "light_blue")
put(2, C, ")", "white")
for col, ch in ((19, "."), (42, "."), (66, "."), (88, ".")):
    put(3, col, ch, "light_blue")
for col, ch in ((3, "*"), (104, "*")):
    put(4, col, ch, "light_blue")
# the back row: twelve people, arm in arm (teal, farther away)
n = 12
width = n * 3 + (n - 1) * 3
start = C - width // 2
for k in range(n):
    x = start + k * 6
    put(5, x + 1, "o", "cyan")
    put(6, x, "/|\\", "cyan")
    put(7, x + 1, "|", "cyan")
    put(8, x, "/ \\", "cyan")
    if k < n - 1:
        put(6, x + 3, "___", "cyan")
# the fire
for row, text in ((9, "("), (10, ")  )"), (11, "(  (  )"), (12, ") ( ) ( ("), (13, "( ) ( ) ( )"), (14, "( )( )( )( )")):
    put(row, C - len(text) // 2, text, "yellow")
put(12, C, ")", "light_red")
put(13, C - 1, "(", "light_red")
put(14, C, "(", "light_red")
put(15, C - 7, "(___)(___)(___)", "brown")
put(16, C - 6, r"\___________/", "cyan")
# the front row: four on each side, hand in hand, the inner ones reaching toward the fire
arms = r"/|\______" * 3 + "/|\\"
left = C - 7 - 3 - len(arms) - 1
right = C + 7 + 3 + 1
put(14, left, arms + "_", "light_cyan")
put(14, right, "_" + arms, "light_cyan")
for x in (left, left + 9, left + 18, left + 27):
    put(13, x + 1, "O", "light_cyan")
    put(15, x + 1, "|", "light_cyan")
    put(16, x, "/ \\", "light_cyan")
for x in (right + 1, right + 10, right + 19, right + 28):
    put(13, x + 1, "O", "light_cyan")
    put(15, x + 1, "|", "light_cyan")
    put(16, x, "/ \\", "light_cyan")
# the ground, and the line underneath
centered(19, "~  " * 33 + "~", "cyan")
for col in (11, 27, 46, 61, 80, 96):
    put(20, col, ",", "green")
centered(22, spaced("NOBODY MAKES IT ALONE"), "light_cyan")


def build():
    out = ["# People First: the main-menu art of the patched build (generated by engine/make_title.py; edit that, not this).",
           "# 108 columns x 24 lines (engine patch 25 centers it on its widest line and draws what fits)."]
    for r in range(H):
        segs, cur, buf = [], None, ""
        for c in range(W):
            ch = grid[r][c]
            k = color[r][c] if ch != " " else (cur or "light_cyan")
            if k != cur and buf:
                segs.append((cur, buf))
                buf = ""
            cur = k
            buf += ch
        if buf:
            segs.append((cur, buf))
        out.append("".join(f"<color_{k}>{t}</color>" for k, t in segs))
    return out


if __name__ == "__main__":
    lines = build()
    path = os.path.join(HERE, "people_first.title")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    for r in range(H):
        print(f"{r:2} |" + "".join(grid[r]) + "|")
    print(f"\nwrote {path} ({H} lines)")
